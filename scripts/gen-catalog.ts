// Regenerates crates/health-core/data/metrics.tsv from the web catalog.
// Usage: bun scripts/gen-catalog.ts <path to web repo>   (default ~/Documents/GitHub/pre-pol/market/health)
import { homedir } from "node:os";
import { join } from "node:path";
import { writeFileSync } from "node:fs";

const web = process.argv[2] ?? join(homedir(), "Documents/GitHub/pre-pol/market/health");
const m = join(web, "src/client/lib/health/metrics");
const { CATALOG } = await import(join(m, "catalog.data.ts"));
const { BODY_METRICS } = await import(join(m, "body.ts"));
const { LAB_METRICS } = await import(join(m, "lab.ts"));
const { FD_METRICS } = await import(join(m, "fd.ts"));
const { groupOf } = await import(join(web, "src/client/export-groups.ts"));
const seen = new Set<string>();
const lines = ["# code\tname\tunit\tagg\tgroup  (group = web export-groups.ts groupOf; generated by scripts/gen-catalog.ts; sources: mirobody Apache-2.0, LOINC per https://loinc.org/license/)"];
for (const [code, name, unit, agg] of [...CATALOG, ...BODY_METRICS, ...LAB_METRICS, ...FD_METRICS]) {
  if (seen.has(code)) continue;
  seen.add(code);
  for (const f of [code, name, unit]) if (/[\t\n]/.test(f)) throw new Error(`tab/newline in ${code}`);
  lines.push([code, name, unit, agg, groupOf({ code, name, unit })].join("\t"));
}
writeFileSync(new URL("../crates/health-core/data/metrics.tsv", import.meta.url), lines.join("\n") + "\n");
console.log(`${seen.size} metrics`);
